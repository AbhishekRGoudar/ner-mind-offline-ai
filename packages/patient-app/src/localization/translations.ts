/**
 * Dynamic content adaptive performance feedback
 */
export function getLocalizedPerformanceFeedback(
  type: 'better' | 'consistent' | 'levelUp',
  lang: SupportedLanguage
): string {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  switch (type) {
    case 'better':
      return dict['feedback.betterThanPrevious'] || TRANSLATIONS.en['feedback.betterThanPrevious'];
    case 'consistent':
      return dict['feedback.consistentEffort'] || TRANSLATIONS.en['feedback.consistentEffort'];
    case 'levelUp':
      return dict['feedback.difficultyUp'] || TRANSLATIONS.en['feedback.difficultyUp'];
  }
}

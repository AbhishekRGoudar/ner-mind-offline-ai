export function getTranslation(lang: SupportedLanguage, key?: string): any {
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  if (!key) {
    const structured: any = { ...dict };
    for (const [k, v] of Object.entries(dict)) {
      const parts = k.split('.');
      if (parts.length === 2) {
        if (!structured[parts[0]]) structured[parts[0]] = {};
        structured[parts[0]][parts[1]] = v;
      }
    }
    return structured;
  }
  return dict[key] || TRANSLATIONS.en[key] || key;
}

export function formatBilingualText(
  primary: string,
  secondary: string | undefined,
  lang: SupportedLanguage
): string {
  if (lang === 'en' || !secondary || primary === secondary) {
    return primary;
  }
  return `${primary} (${secondary})`;
}

